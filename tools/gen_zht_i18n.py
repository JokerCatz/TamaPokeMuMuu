#!/usr/bin/env python3
"""Adds Traditional Chinese (Taiwan, LANG_ZHT) to i18n.cpp by converting the Simplified Chinese rows (LANG_ZH) with OpenCC (s2twp: Taiwan characters AND Taiwan phrases:
软件 -> 軟體, 信息 -> 資訊 ...), then applying tools/zht_overrides.txt (one `simplified-or-converted => wanted` per line) for game terms the converter gets wrong.
The result is written between `// ZHT-BEGIN` / `// ZHT-END` markers, so the script is idempotent and the generated rows are reviewable in the diff.
  pip install opencc-python-reimplemented
  python3 tools/gen_zht_i18n.py
Only the Chinese characters change: format specifiers, ASCII and punctuation are left alone."""
import os, re, sys
import opencc
HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.join(HERE, '..')
cc = opencc.OpenCC('s2twp')
OVR = []
p = os.path.join(HERE, 'zht_overrides.txt')
if os.path.exists(p):
    for l in open(p, encoding='utf-8'):
        l = l.split('#')[0].strip()
        if '=>' in l: a, b = [x.strip() for x in l.split('=>', 1)]; OVR.append((a, b))
STR = re.compile(r'"((?:[^"\\]|\\.)*)"')
CJK = re.compile(r'[一-鿿]')
def conv(m):
    t = m.group(1)
    if not CJK.search(t): return m.group(0)
    for a, b in OVR: t = t.replace(a, b)        # overrides on the Simplified text first (whole-word, before OpenCC splits phrases)
    t = cc.convert(t)
    for a, b in OVR: t = t.replace(a, b)        # and on the converted text
    return '"' + t + '"'
def block(src, name):
    m = re.search(r'static const char \*const ' + re.escape(name) + r'\[LANG_COUNT\]\[[A-Z_]+\] = \{', src)
    i = src.index('\n};\n', m.end())
    return m, i
def strip_old(src):
    return re.sub(r'\n?[ \t]*// ZHT-BEGIN.*?// ZHT-END[^\n]*\n', '\n', src, flags=re.S)
def wifi():
    """wifisync.cpp: the Wi-Fi setup page and the /save answers in Traditional Chinese (PAGINA_ZHT, the third entry of MSG_*), between ZHT markers."""
    path = os.path.join(ROOT, 'wifisync.cpp'); src = strip_old(open(path, encoding='utf-8').read())
    m = re.search(r'static const char PAGINA_ZH\[\] PROGMEM = R"\((.*?)\)";\n', src, re.S)
    page = STR_ALL(m.group(1))
    block = '\n// ZHT-BEGIN (generated by tools/gen_zht_i18n.py from PAGINA_ZH)\nstatic const char PAGINA_ZHT[] PROGMEM = R"(' + page + ')";\n// ZHT-END\n'
    src = src[:m.end()] + block + src[m.end():]
    for name in ('MSG_CHESS', 'MSG_BAD', 'MSG_SAVED'):
        m = re.search(r'static const char \*const ' + name + r'\[LANG_COUNT\] = \{', src)
        end = src.index('\n};\n', m.end())
        body = src[m.end():end]
        zh = [l for l in body.rstrip().split('\n') if CJK.search(l)][-1]       # the Simplified Chinese entry (the last line with Chinese)
        src = src[:end] + '\n  // ZHT-BEGIN\n' + STR.sub(conv, zh) + '\n  // ZHT-END' + src[end:]
    open(path, 'w', encoding='utf-8').write(src)
    print('wifisync.cpp: ZHT page + messages written')


def STR_ALL(text):
    for a, b in OVR: text = text.replace(a, b)
    return cc.convert(text)


def main():
    wifi()
    path = os.path.join(ROOT, 'i18n.cpp'); src = strip_old(open(path, encoding='utf-8').read())
    out = src
    for name in ('MED_DSC', 'MED_LBL', 'MED_NAME', 'STRINGS'):     # later arrays first: the earlier offsets stay valid
        m, end = block(out, name)
        body = out[m.end():end]
        if name == 'STRINGS':
            k = body.index('// ---------------- ZH ----------------')
            zh = body[k:]
            row = re.sub(r'// -+ ZH -+', '// ---------------- ZHT (Traditional Chinese, Taiwan: generated by tools/gen_zht_i18n.py from the ZH row) ----------------', zh, 1)
            row = re.sub(r'\n\s*// Chino simplificado.*?\n\s*\{', '\n  {', row, 1, flags=re.S)   # the Spanish note about GB2312 belongs to the Simplified row
        else:
            last = body.rstrip().rsplit('\n  { ', 1)               # the last row is the ZH one
            row = '  { ' + last[1] if len(last) == 2 else body
        row = STR.sub(conv, row)
        ins = '\n  // ZHT-BEGIN\n' + row.rstrip('\n') + '\n  // ZHT-END\n'
        if not body.endswith('\n'): ins = '\n' + ins
        out = out[:end] + ins.rstrip('\n') + out[end:]
    open(path, 'w', encoding='utf-8').write(out)
    print('i18n.cpp: ZHT rows written')
if __name__ == '__main__': main()
